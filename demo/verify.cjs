const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('demo/dist/app.js','utf8');
let saved=null;
function boot(){
 const nodes=new Map();
 const el=()=>({innerHTML:'',textContent:'',value:'',style:{},dataset:{},classList:{add(){},remove(){},toggle(){}},addEventListener(){},setAttribute(){},after(){},before(){},remove(){},showModal(){this.open=true},close(){this.open=false},querySelectorAll(){return[];}});
 const get=s=>{if(!nodes.has(s))nodes.set(s,el());return nodes.get(s)};
 const context=vm.createContext({console,Date,Map,Set,Object,Array,String,Number,JSON,crypto:require('node:crypto').webcrypto,setTimeout:()=>0,clearTimeout(){},window:{},document:{querySelector:get,querySelectorAll:()=>[],createElement:el,addEventListener(){},body:{append(){}}},localStorage:{getItem:()=>saved,setItem:(k,v)=>saved=v}});
 vm.runInContext(source,context);
 return {run:code=>vm.runInContext(code,context),get,failStorage:()=>context.localStorage.setItem=()=>{throw Error('quota')}};
}
let app=boot();
app.run("selected.add('乏力');ratings['乏力']=3;occurrenceParts.set('乏力',new Set(['全身']));");
app.run("tagNotes.set('乏力','<script>example</script>');expandedTag='乏力';renderSelected();");
assert.ok(app.get('#selected').innerHTML.includes('&lt;script&gt;example&lt;/script&gt;'));
app.run("selected.add('焦虑');expandedTag='焦虑';renderSelected();expandedTag='乏力';renderSelected();selected.delete('焦虑');");
assert.ok(app.get('#selected').innerHTML.includes('&lt;script&gt;example&lt;/script&gt;')); 
app.get('#save').onclick();
assert.equal(JSON.parse(saved).records[0].tags[0].rating,3);
assert.equal(JSON.parse(saved).records[0].tags[0].note,'<script>example</script>');
assert.equal(app.run('tagNotes.size'),0);
assert.ok(app.get('#history').innerHTML.includes('全身'));
assert.ok(!app.get('#history').innerHTML.includes('<script>'));
app=boot();
assert.equal(app.run('records.length'),1);
assert.ok(app.get('#history').innerHTML.includes('乏力'));
app.run("activateDate('2026-10-03')");
assert.equal(app.run('reviewDay'),'2026-10-03');
assert.equal(app.run('selectingDates'),false);
app.run("activateDate('2026-10-03',true);activateDate('2026-10-08')");
assert.equal(app.run('rangeStart'),'2026-10-03');
assert.equal(app.run('rangeEnd'),'2026-10-08');
assert.equal(app.run('selectingDates'),true);
assert.equal(app.get('#selection-tools').hidden,false);
app.run("activateDate('2026-09-29')");
assert.equal(app.run('rangeStart'),'2026-09-29');
assert.equal(app.run('rangeEnd'),'2026-10-03');
app.get('#cancel-selection').onclick();
assert.equal(app.run('selectingDates'),false);
assert.equal(app.get('#selection-tools').hidden,true);
app.run("chooseRange(dayKey(new Date()),dayKey(new Date()))");
assert.ok(app.get('#history').innerHTML.includes('程度 3/5'));
app.get('#report-start').value='2099-01-01';app.get('#report-end').value='2099-01-02';app.get('#report-start').onchange();
assert.ok(app.get('#history').innerHTML.includes('暂无记录'));
app.get('#report-start').value='2099-02-01';app.get('#report-start').onchange();
assert.ok(app.get('#history').innerHTML.includes('有效的起止日期'));
app.run("selected.add('自伤念头 / 冲动');expandedTag='自伤念头 / 冲动';renderSelected();");
assert.ok(app.get('#selected').innerHTML.includes('data-rating="5"'));
assert.ok(app.get('#selected').innerHTML.includes('这次的强烈程度'));
app.run("ratings['自伤念头 / 冲动']=2;tagNotes.set('自伤念头 / 冲动','个人补充');");
app.get('#save').onclick();
assert.equal(JSON.parse(saved).records[0].tags[0].rating,2);
assert.equal(JSON.parse(saved).records[0].tags[0].note,'个人补充');
app.run("records.push({date:new Date().toISOString(),tags:[{name:'疲惫',parts:[],rating:1}],thoughts:[],note:'旧版整条记录的补充'});selectingDates=false;reviewDay=dayKey(new Date());renderReview();");
assert.ok(app.get('#history').innerHTML.includes('旧版整条记录的补充'));
// Editing updates exactly one record and restores the pre-existing draft.
const target=app.run('records[0].id');
const originalTime=app.run('records[0].date');
app.run("selected.add('平静');tagNotes.set('平静','还没记下的草稿');expandedTag='平静';");
app.run(`beginEditing(${JSON.stringify(target)})`);
assert.equal(app.run('editingId'),target);
app.run("ratings['自伤念头 / 冲动']=4;tagNotes.set('自伤念头 / 冲动','修改后的补充');");
const beforeEdit=app.run('records.length');
app.get('#save').onclick();
assert.equal(app.run('records.length'),beforeEdit);
assert.equal(app.run('records[0].tags[0].rating'),4);
assert.equal(app.run('records[0].tags[0].note'),'修改后的补充');
assert.equal(app.run('records[0].date'),originalTime);
assert.equal(app.run("tagNotes.get('平静')"),'还没记下的草稿');
assert.equal(app.run('editingId'),null);
app.run(`beginEditing(${JSON.stringify(target)});ratings['自伤念头 / 冲动']=1;`);
app.get('#cancel-edit').onclick();
assert.equal(app.run('records[0].tags[0].rating'),4);
assert.equal(app.run("tagNotes.get('平静')"),'还没记下的草稿');
// Date changes move an edited record to the correct day.
app.run(`beginEditing(${JSON.stringify(target)})`);
app.get('#occurred').value='2026-10-01T10:30';app.get('#save').onclick();
assert.equal(app.run('reviewDay'),'2026-10-01');
assert.ok(app.get('#history').innerHTML.includes('修改后的补充'));
// Opening/cancelling the deletion confirmation does not mutate data.
app.run(`requestDelete(${JSON.stringify(target)})`);
assert.equal(app.get('#delete-dialog').open,true);
assert.equal(app.run('records.length'),beforeEdit);
app.get('#cancel-delete').onclick();
assert.equal(app.run('records.length'),beforeEdit);
app.run(`requestDelete(${JSON.stringify(target)});confirmDelete()`);
assert.equal(app.run('records.length'),beforeEdit-1);
assert.equal(app.run('deletedRecords.length'),1);
assert.equal(JSON.parse(saved).deletedRecords.length,1);
app=boot();assert.equal(app.get('#undo-delete').hidden,false);
app.get('#undo-delete').onclick();
assert.equal(app.run('records.length'),beforeEdit);
assert.equal(app.run('records[0].id'),target);
assert.equal(app.run('reviewDay'),'2026-10-01');
assert.equal(app.run('deletedRecords.length'),0);
// Editing legacy notes remains possible, and a failed write rolls back edits/deletion.
app.run("records.push({id:'legacy',date:new Date().toISOString(),tags:[],thoughts:[],note:'原有补充'});beginEditing('legacy');");
assert.equal(app.get('#legacy-note-field').hidden,false);
app.get('#legacy-note').value='旧补充已修改';app.get('#save').onclick();
assert.equal(app.run("records.find(r=>r.id==='legacy').note"),'旧补充已修改');
app.run(`beginEditing(${JSON.stringify(target)});ratings['自伤念头 / 冲动']=5;`);app.failStorage();app.get('#save').onclick();
assert.equal(app.run('records[0].tags[0].rating'),4);
assert.equal(app.run('editingId'),target);
app.get('#cancel-edit').onclick();
app.run(`requestDelete(${JSON.stringify(target)});confirmDelete()`);
assert.equal(app.run('records[0].id'),target);
assert.equal(app.run('deletedRecords.length'),0);
console.log('PASS: previous regressions; edit/save/cancel, timestamps, moving dates, draft restoration, legacy notes, confirmed deletion, persistent undo and storage failure rollback');
